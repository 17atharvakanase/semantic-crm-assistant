import pandas as pd


def execute_query(deals_df, resolved_filters):
    """
    Executes the CRM query by applying resolved filters
    to the deals DataFrame.

    Args:
        deals_df (pd.DataFrame):
            Complete CRM dataset.

        resolved_filters (dict):
            CRM-specific filters generated by the semantic resolver.

    Returns:
        pd.DataFrame:
            Filtered records matching the query.
    """

    filtered_df = deals_df.copy()

    for field, values in resolved_filters.items():

        # Skip fields that don't exist
        if field not in filtered_df.columns:
            continue

        # Ensure values is always a list
        if not isinstance(values, list):
            values = [values]

        filtered_df = filtered_df[
            filtered_df[field].isin(values)
        ]

    return filtered_df